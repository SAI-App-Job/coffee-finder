export function getGradeExplanation(grade, country, designatedBrand) {
  if (!grade) return null;

  // ブルーマウンテンは国別グレードとは別の、銘柄固有の等級体系
  if (designatedBrand === "ブルーマウンテン" && /No\.?\s*\d/i.test(grade)) {
    return "ジャマイカ・ブルーマウンテン地区独自の等級。No.1が最上位(木樽出荷)で、No.2、No.3と続き、規格外はピーベリー・トリアージとして扱われる。";
  }

  if (/^G[1-6]$/.test(grade)) {
    if (country === "エチオピア") {
      return `エチオピアの${grade}は欠点数(300gあたり)による格付け。G1は欠点0〜3個の最高等級で、地域・精選方法によっては特別に扱われることも。数字が大きいほど欠点が多い。`;
    }
    if (country === "インドネシア") {
      return `インドネシアの${grade}も欠点数による格付けだが、基準はエチオピアより緩め(G1で欠点0〜11個程度)。同じ「G1」でも国によって意味する品質水準が異なる点に注意。`;
    }
    return `欠点数による格付け(数字が小さいほど高品質)。ただし基準は生産国ごとに異なる。`;
  }

  if (grade === "AA") {
    return "スクリーンサイズ(豆の粒の大きさ)による格付け。ケニア・タンザニアで使われる代表的な表記で、AAは大粒の等級を示す。粒の大きさは必ずしも風味の良さを保証しない。";
  }

  if (/^SHB$/.test(grade)) {
    return "Strictly Hard Bean。標高の高さで格付けする表記で、グアテマラやコスタリカでは標高1,350m前後以上が目安。標高が高いほど豆が硬く締まり、高品質とされる。";
  }

  if (/^No\.?\s*\d+$/i.test(grade)) {
    return "生産地・店舗によって意味が異なる通し番号やロット表記。ブラジルでは欠点数による等級(No.2〜8)を指すことが多い。";
  }

  return "国別グレードは、標高・スクリーンサイズ(粒の大きさ)・欠点数など、生産国ごとに異なる基準で決まる。同じ表記でも国が違えば意味が異なることがある。";
}
