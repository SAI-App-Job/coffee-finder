// 商品のテイスティングノートから、風味の語を探す(否定の除外つき)。
// 「酸味がなく」「甘さはない」「酸味を感じない」のように、語の直後で否定されている出現は、その語が「ある」とは数えない。
// 語のすべての出現が否定されている場合だけ、その語は無し。
// 導入範囲は「無い系」のみ。「控えめ」「少ない」「抑えた」などの弱い表現は、除外しない(まだ「ある」と数える)。
// 語と否定が直接つながる形だけを見る(例: 「コクがあって飽きない」の「コク」は、否定しない)。
const NEGATION = new RegExp(
  "^[：:]?\s*[はがもを]?\s*(?:" +
    "なし|ゼロ|皆無|ありません|" +
    "(?:ほとんど|ほぼ|全く|まったく|全然|あまり|決して)?\s*(?:" +
    "感じ(?:ない|ません|られない|られません|ず)|" +
    "(?:強|濃|目立|出|ある|あり|多)くな(?:い|く)|" +
    // 「なくちあたり」(口当たり)・「フレッシュないちご」を否定と誤らない
    "な(?:い|く)(?!ち)" +
    ")" +
    ")"
);

/** 否定されていない出現が1つでもあれば、その表記を返す。無ければ null。text は小文字にしておく */
export function findAffirmedWord(lowerText, words) {
  for (const w of words) {
    let i = lowerText.indexOf(w);
    while (i >= 0) {
      if (!NEGATION.test(lowerText.slice(i + w.length, i + w.length + 16))) return w;
      i = lowerText.indexOf(w, i + 1);
    }
  }
  return null;
}
