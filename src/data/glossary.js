function validateGlossaryTerms() {
  const missing = GLOSSARY_TERMS.filter((t) => !t.source);
  if (missing.length > 0) {
    throw new Error(
      "[glossary] source未設定のエントリが見つかりました。出典を明記してください: " +
        missing.map((t) => t.term).join(" / ")
    );
  }
}

